_JAPANESE = "jpn"


def _convert_examples() -> None:
    bind = op.get_bind()
    texts: defaultdict[int, list[tuple[str, str]]] = defaultdict(list)
    for example_id, lang, text in bind.execute(
        sa.select(
            _example_sentences.c.example_id,
            _example_sentences.c.lang,
            _example_sentences.c.text,
        ).order_by(_example_sentences.c.example_id, _example_sentences.c.position)
    ):
        texts[example_id].append((lang, text))
    forms = _enabled_forms(bind)

    sentences: list[dict[str, Any]] = []
    translations: list[dict[str, Any]] = []
    words: list[dict[str, Any]] = []
    examples = bind.execute(
        sa.select(
            _examples,
            _senses.c.entry_id,
            _entries.c.user_id,
            _entries.c.created_at,
            _entries.c.updated_at,
        )
        .join(_senses, _senses.c.id == _examples.c.sense_id)
        .join(_entries, _entries.c.id == _senses.c.entry_id)
        .order_by(_entries.c.id, _senses.c.position, _examples.c.position)
    )
    for row in examples:
        japanese = next((t for lang, t in texts[row.id] if lang == _JAPANESE), None)
        if not japanese or not japanese.strip():
            continue  # never stored without one; nothing to convert
        japanese = japanese.strip()
        sentences.append(
            {
                "id": row.id,
                "user_id": row.user_id,
                "text": japanese,
                "is_active": row.enabled,
                "origin": row.origin,
                "original_id": row.original_id,
                "source_id": row.source_id,
                "edited_id": row.edited_id,
                "revision": row.revision,
                "source_collection_ids": row.source_collection_ids,
                "created_at": row.created_at,
                "updated_at": row.updated_at,
            }
        )
        translations += [
            {"sentence_id": row.id, "position": i, "lang": lang, "text": text}
            for i, (lang, text) in enumerate(
                (lang, t) for lang, t in texts[row.id] if lang != _JAPANESE
            )
        ]
        candidates = [row.text] if row.text else forms[row.entry_id]
        start, end = _span(japanese, candidates)
        words.append(
            {
                "sentence_id": row.id,
                "position": 0,
                "span_start": start,
                "span_end": end,
                "pos": [],
                "entry_id": row.entry_id,
                "sense_id": row.sense_id,
            }
        )
    if sentences:
        op.bulk_insert(_sentences, sentences)
        op.bulk_insert(_translations, translations)
        op.bulk_insert(_words, words)
    if bind.dialect.name == "postgresql":
        # Ids were taken from the examples: move the sequence past them.
        op.execute(
            "SELECT setval(pg_get_serial_sequence('practice_sentences', 'id'), "
            "COALESCE(MAX(id), 1), MAX(id) IS NOT NULL) FROM practice_sentences"
        )


def _enabled_forms(bind: sa.Connection) -> defaultdict[int, list[str]]:
    """Each entry's enabled spellings in order, then its enabled readings."""
    forms: defaultdict[int, list[str]] = defaultdict(list)
    columns = ((_spellings, _spellings.c.kanji), (_readings, _readings.c.text))
    for table, column in columns:
        for entry_id, text in bind.execute(
            sa.select(table.c.entry_id, column)
            .where(table.c.enabled)
            .order_by(table.c.entry_id, table.c.position)
        ):
            forms[entry_id].append(text)
    return forms


def _span(text: str, candidates: Sequence[str]) -> tuple[int | None, int | None]:
    """Where the first candidate found in `text` is, or no span."""
    for candidate in candidates:
        start = text.find(candidate) if candidate else -1
        if start >= 0:
            return start, start + len(candidate)
    return None, None
